
-- PETCARE: Esquema relacional H2

CREATE TABLE clientes (
                          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                          nombre VARCHAR(150) NOT NULL,
                          correo VARCHAR(150) NOT NULL UNIQUE,
                          telefono VARCHAR(20),
                          activo BOOLEAN NOT NULL
);

CREATE TABLE mascotas (
                          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                          nombre VARCHAR(100) NOT NULL,
                          especie VARCHAR(50) NOT NULL,
                          raza VARCHAR(100) NOT NULL,
                          fecha_nacimiento DATE NOT NULL,
                          peso DECIMAL(7,2) NOT NULL,
                          activo BOOLEAN NOT NULL,
                          cliente_id BIGINT NOT NULL,

                          CONSTRAINT fk_mascota_cliente
                              FOREIGN KEY (cliente_id) REFERENCES clientes(id),

                          CONSTRAINT ck_mascota_peso CHECK (peso > 0)
);

CREATE TABLE veterinarios (
                              id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                              nombre VARCHAR(150) NOT NULL,
                              especialidad VARCHAR(100) NOT NULL,
                              correo VARCHAR(150) NOT NULL UNIQUE,
                              telefono VARCHAR(20),
                              activo BOOLEAN NOT NULL
);

CREATE TABLE horarios_veterinarios (
                                       id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                       veterinario_id BIGINT NOT NULL,
                                       dia_semana VARCHAR(20) NOT NULL,
                                       hora_inicio TIME NOT NULL,
                                       hora_fin TIME NOT NULL,
                                       activo BOOLEAN NOT NULL,

                                       CONSTRAINT fk_horario_veterinario
                                           FOREIGN KEY (veterinario_id) REFERENCES veterinarios(id),

                                       CONSTRAINT ck_horario_horas CHECK (hora_fin > hora_inicio)
);

CREATE TABLE reservas (
                          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                          mascota_id BIGINT NOT NULL,
                          veterinario_id BIGINT NOT NULL,
                          fecha DATE NOT NULL,
                          hora TIME NOT NULL,
                          motivo VARCHAR(500) NOT NULL,
                          estado VARCHAR(20) NOT NULL DEFAULT 'PENDIENTE',

                          CONSTRAINT fk_reserva_mascota
                              FOREIGN KEY (mascota_id) REFERENCES mascotas(id),

                          CONSTRAINT fk_reserva_veterinario
                              FOREIGN KEY (veterinario_id) REFERENCES veterinarios(id),

                          CONSTRAINT ck_estado_reserva
                              CHECK (estado IN (
                                                'PENDIENTE',
                                                'CONFIRMADA',
                                                'CANCELADA',
                                                'ATENDIDA'
                                  ))
);

CREATE INDEX idx_reserva_agenda
    ON reservas(veterinario_id, fecha, hora);

CREATE TABLE atenciones_medicas (
                                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                    reserva_id BIGINT NOT NULL UNIQUE,
                                    mascota_id BIGINT NOT NULL,
                                    veterinario_id BIGINT NOT NULL,
                                    fecha_atencion TIMESTAMP NOT NULL,
                                    diagnostico VARCHAR(2000) NOT NULL,
                                    tratamiento VARCHAR(4000) NOT NULL,

                                    CONSTRAINT fk_atencion_reserva
                                        FOREIGN KEY (reserva_id) REFERENCES reservas(id),

                                    CONSTRAINT fk_atencion_mascota
                                        FOREIGN KEY (mascota_id) REFERENCES mascotas(id),

                                    CONSTRAINT fk_atencion_veterinario
                                        FOREIGN KEY (veterinario_id) REFERENCES veterinarios(id)
);

CREATE TABLE medicamentos_prescritos (
                                         id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                         atencion_id BIGINT NOT NULL,
                                         nombre_medicamento VARCHAR(150) NOT NULL,
                                         dosis VARCHAR(100) NOT NULL,
                                         frecuencia VARCHAR(100) NOT NULL,
                                         duracion_dias INTEGER NOT NULL,
                                         indicaciones VARCHAR(500),

                                         CONSTRAINT fk_medicamento_atencion
                                             FOREIGN KEY (atencion_id) REFERENCES atenciones_medicas(id),

                                         CONSTRAINT ck_duracion_dias
                                             CHECK (duracion_dias > 0)
);
